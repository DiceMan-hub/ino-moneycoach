# データを直接定義（CSVファイルから読み込んだ内容）
def parse_csv_content(content):
    """CSVファイルの内容をパース"""
    data = []
    lines = content.strip().split('\n')
    
    # ヘッダー行をスキップ（最初の3行）
    for line in lines[3:]:
        if not line.strip():
            continue
        
        # CSV形式をパース（引用符を考慮）
        match = re.match(r'"([^"]+)"\s*,\s*"(\d+)"', line)
        if match:
            date_str = match.group(1).replace('T00:00:00', '').replace('T01:00:00', '')
            try:
                date_obj = datetime.strptime(date_str[:10], '%Y-%m-%d')
                value = int(match.group(2))
                data.append({'Date': date_str[:10], 'Value': value, 'DateObj': date_obj})
            except:
                continue
    
    return data

